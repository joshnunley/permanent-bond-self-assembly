"""Exact search for one n: every prefix F(1..N_max) of a merge-closed family of regular n-gon bodies, under the coin
form of overlap, compared with the listed families at every N <= N_max.  (proofs/fixed-side-count.md)

Centres are integer vectors in
Z[exp(i pi / n)], touching and congruence are decided exactly, and the only inequality (two centres less than 1
apart) is decided with a certified sign. Overlap is relaxed to the coin condition, which keeps a superset of the
n-gon prefixes; so the analytic continuation lemmas apply to every infinite family when all surviving prefixes match.

Candidates are generated by placing a new cell across each free edge.

usage: python3 -B exact_n.py n N_max [--require-match]
"""
from argparse import ArgumentParser
import sys
import time
from collections import Counter

from exact_core import CycField, Bodies, family_search, ngon_candidates


def chain_from_word(F, word, t):
    """Centres of the chain with turn word `word` (letters -1, 0, +1), each turn being t steps of 2 pi / Q."""
    cells = [F.zero, F.one]
    e = 0
    for s in word:
        e += s * t
        cells.append(F.add(cells[-1], F.pw[e % F.Q]))
    return cells


def valid_body(Rg, cells):
    if len(set(cells)) < len(cells):
        return False
    for i in range(len(cells)):
        if not Rg.valid_new(cells[:i], cells[i]):
            return False
    return True


def listed(Rg, n, Nmax):
    """name -> [None, shape id of S(1), ..., S(Nmax)]; a sequence stops (None) when the body breaks the coin
    condition or repeats a centre."""
    F = Rg.F
    fams = {}
    if n % 2 == 0:
        fams["row"] = lambda N: chain_from_word(F, [0] * (N - 2), 0)[:N]
    for k in range(1, (n + 1) // 2):
        if 2 * k == n:
            continue
        t = n - 2 * k
        fams[f"Z({n},{k})"] = lambda N, t=t: chain_from_word(F, [(-1) ** i for i in range(N - 2)], t)[:N]
        fams[f"arc({n},{k})"] = lambda N, t=t: chain_from_word(F, [1] * (N - 2), t)[:N]
    if n % 2 == 0:
        for j in range(1, n // 4 + 1):
            if 6 * j < n:
                continue
            v = F.pw[2 * j]
            def strip(N, variant, v=v):
                m = N // 2
                bottom = [F.from_poly({0: i}) for i in range(m + 1)]
                top = [F.add(b, v) for b in bottom]
                cells = bottom[:m] + top[:m]
                if N % 2:
                    cells.append(bottom[m] if variant == "E" else top[m])
                return cells
            fams[f"ladder {360 * j / n:.1f} E"] = lambda N, s=strip: s(N, "E")
            fams[f"ladder {360 * j / n:.1f} T"] = lambda N, s=strip: s(N, "T")
    out = {}
    for name, f in fams.items():
        seq = [None]
        dead = False
        for N in range(1, Nmax + 1):
            if not dead:
                b = f(N)
                if not valid_body(Rg, b):
                    dead = True
            seq.append(None if dead else Rg.shape(Rg.add(b)))
        if Nmax < 3 or seq[3] is not None:
            out[name] = seq
    return out


def main(n, Nmax):
    t0 = time.time()
    F = CycField(2 * n)
    # Each centre is a sum of at most Nmax-1 unit vectors from a contact path.
    # The n-gon search's vector operations rotate, translate or subtract such
    # centres. This bound covers their integer dot products and accumulations.
    height = max(abs(c) for root in F.pw for c in root)
    if 100 * Nmax * F.phi * height**2 >= 2**63:
        raise ArithmeticError("coordinate bound exceeds the int64 budget")
    Rg = Bodies(F)
    reach, fams = family_search(Rg, Nmax, ngon_candidates(Rg, n))
    L = listed(Rg, n, Nmax)
    by_seq = {}
    for name, seq in L.items():
        if seq[Nmax] is not None:
            by_seq.setdefault(tuple(seq[1:]), []).append(name)
    print(f"n = {n}, N_max = {Nmax}, exact arithmetic in Z[zeta_{2 * n}], coin overlap, candidates: ngon")
    print(f"  {len(fams)} prefixes reach N_max  ({time.time() - t0:.0f} s, {len(Rg.bodies)} bodies met, "
          f"{F.hp_calls} high-precision comparisons)")
    print("  N:                 " + " ".join(f"{N:5d}" for N in sorted(reach)))
    print("  prefixes reaching: " + " ".join(f"{reach[N]:5d}" for N in sorted(reach)))
    matched = Counter()
    unmatched = []
    for Fam in fams:
        sig = tuple(Rg.shape(Fam[N][0]) for N in range(1, Nmax + 1))
        if sig in by_seq:
            matched[" = ".join(by_seq[sig])] += 1
        else:
            unmatched.append(Fam)
    print("  prefixes whose shapes S(1..N_max) are those of a listed family, at every N:")
    for name in sorted(matched):
        print(f"    {name}: {matched[name]} prefixes")
    missing = [" = ".join(v) for s, v in by_seq.items() if " = ".join(v) not in matched]
    print(f"  listed sequences with no surviving prefix: {missing if missing else 'none'}")
    print(f"  unmatched prefixes: {len(unmatched)}")
    seen = set()
    for Fam in unmatched:
        sig = tuple(Rg.shape(Fam[N][0]) for N in range(1, Nmax + 1))
        if sig in seen:
            continue
        seen.add(sig)
        first_nc = next((N for N in range(3, Nmax + 1) if not Rg.is_chain(Fam[N][0])), None)
        print(f"    first non-chain at N = {first_nc}; contact degrees of S({Nmax}): {Rg.degrees(Fam[Nmax][0])}")
    sys.stdout.flush()
    return len(unmatched)


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("n", type=int)
    parser.add_argument("stock", type=int)
    parser.add_argument("--require-match", action="store_true", help="fail if any prefix falls outside the comparison list")
    args = parser.parse_args()
    if args.n < 3 or args.stock < 3:
        parser.error("both n and the stock bound must be at least three")
    unmatched = main(args.n, args.stock)
    if args.require_match and unmatched:
        sys.exit(1)
